    PARENT_ATTRIBUTABLE = {
        'net_income': lambda label: any(
            f"{term} attributable to" in label for term in ("net income", "net earnings", "profit")
        ),
        'total_equity': lambda label: "liabilities" not in label and (
            (label.startswith("total") and ("shareholders' equity" in label or "stockholders' equity" in label))
            or "share of equity" in label
            or "equity attributable to" in label
        ),
    }

    # Labels a field's substring match must never land on.
    SUBSTRING_EXCLUDES = {
        'revenue': ("cost of",),
        'net_income': ("per share", "per common share", "per diluted", "noncontrolling", "non-controlling"),
        'total_equity': ("liabilities",),
    }

    @staticmethod
    def normalize_label(label: str) -> str:
        """
        Canonical row label: lowercase, straight quotes, no parentheticals
        ("net cash provided by/(used in) ..." -> "net cash provided by ..."),
        no trailing footnote marker ("profit 1" -> "profit"), single spaces.
        """
        text = label.lower().replace("\u2019", "'").replace("\u2018", "'")
        text = re.sub(r"\([^)]*\)", " ", text).replace("/", " ")
        text = re.sub(r"\s+(?:\d{1,2}|[a-z]|\*+)$", "", text.strip().rstrip(":").strip())
        return re.sub(r"\s+", " ", text).strip()

    @classmethod
    def clean_number(cls, text: str) -> Optional[float]:
        """
        Convert text to float, handling various financial formats.
        
        Handles:
        - Commas as thousand separators
        - Dollar signs
        - Parentheses for negative numbers
        - Percentages (returns decimal)
        - Abbreviations (K, M, B)
        
        Args:
            text: String to convert
            
        Returns:
            Float value or None if conversion fails
        """
        if not text or not isinstance(text, str):
            return None
        
        text = text.strip()
        
        if not text or text == '-':
            return None
        
        try:
            # Check for parentheses indicating negative
            is_negative = '(' in text and ')' in text
            
            # Check for percentage
            is_percentage = '%' in text
            
            # Check for abbreviations
            multiplier = 1.0
            upper = text.upper()
            if upper.endswith('K'):
                multiplier = 1e3
            elif upper.endswith('M'):
                multiplier = 1e6
            elif upper.endswith('B'):
                multiplier = 1e9
            
            # Remove all non-numeric characters except decimal point and minus
            cleaned = re.sub(r'[^0-9.-]', '', text)
            
            if not cleaned:
                return None
            
            # Parse number
            value = float(cleaned)
            
            # Apply modifiers
            if is_negative:
                value = -abs(value)
            
            if is_percentage:
                value = value / 100.0
            
            value = value * multiplier
            
            return value
            
        except (ValueError, InvalidOperation) as e:
            logger.debug("number_parse_failed", text=text, error=str(e))
            return None
    
    @classmethod
    def detect_quarterly_data(cls, markdown_content: str) -> bool:
        """
        Detect if financial data is quarterly based on headers.
        
        Args:
            markdown_content: Raw markdown from extraction
            
        Returns:
            True if quarterly data detected
        """
        quarterly_patterns = [
            r'three\s+months\s+ended',
            r'quarterly',
            r'q[1-4]\s+(?:fy|fiscal)',
            r'13\s+weeks\s+ended'
        ]
        
        content_lower = markdown_content.lower()
        
        for pattern in quarterly_patterns:
            if re.search(pattern, content_lower):
                logger.info("quarterly_data_detected", pattern=pattern)
                return True
        
        return False
    
    @classmethod
    def annualize(cls, value: float, is_quarterly: bool) -> float:
        """
        Annualize quarterly financial data.
        
        Args:
            value: Financial value
            is_quarterly: Whether data is quarterly
            
        Returns:
            Annualized value
        """
        if not is_quarterly or value is None:
            return value
        
        return value * 4.0
    
    @classmethod
    def find_field_value(
        cls,
        data_map: Dict[str, str],
        field_name: str,
        default: Optional[float] = None
    ) -> Optional[float]:
        """
        Find value in data map using field synonyms.
        
        Args:
            data_map: Dictionary of extracted values
            field_name: Name of field to find
            default: Default value if not found
            
        Returns:
            Found value or default
        """
        synonyms = cls.FIELD_SYNONYMS.get(field_name, [field_name])
        labels = [(cls.normalize_label(key), val) for key, val in data_map.items()]
        excludes = cls.SUBSTRING_EXCLUDES.get(field_name, ())

        def first_number(matches):
            for label, val_str in labels:
                if matches(label) and not any(x in label for x in ("noncontrolling", "non-controlling")):
                    val = cls.clean_number(val_str)
                    if val is not None:
                        return val
            return None

        # Prefer amounts attributable to the company over consolidated totals
        # that include noncontrolling interests (e.g. "net income attributable to Walmart").
        if field_name in cls.PARENT_ATTRIBUTABLE:
            val = first_number(cls.PARENT_ATTRIBUTABLE[field_name])
            if val is not None:
                return val

        # Exact label match, in synonym priority order
        for synonym in synonyms:
            if synonym.startswith("~"):
                continue
            term = cls.normalize_label(synonym.lstrip("="))
            for label, val_str in labels:
                if label == term:
                    val = cls.clean_number(val_str)
                    if val is not None:
                        return val

        # Label patterns ('~' prefix): regex over the normalized label
        for synonym in synonyms:
            if synonym.startswith("~"):
                val = first_number(lambda label, pattern=synonym[1:]: re.search(pattern, label) is not None)
                if val is not None:
                    return val

        # Substring match ('='-prefixed synonyms are exact-only)
        for synonym in synonyms:
            if synonym.startswith(("=", "~")):
                continue
            term = cls.normalize_label(synonym)
            for label, val_str in labels:
                if term in label and not any(x in label for x in excludes):
                    val = cls.clean_number(val_str)
                    if val is not None:
                        return val

        return default
