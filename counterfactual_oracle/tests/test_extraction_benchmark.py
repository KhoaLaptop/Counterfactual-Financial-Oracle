"""
Tests for the PDF-extractor accuracy benchmark (ground truth = SEC XBRL).
"""

from datetime import date

import pytest

from counterfactual_oracle.src.parsers.benchmark import (
    edgar_truth,
    markdown_numbers,
    run_benchmark,
    summarize,
)


def _e(start, end, val, form="10-Q", filed="2025-08-01"):
    entry = {"end": end, "val": val, "form": form, "filed": filed}
    if start:
        entry["start"] = start
    return entry


def _facts():
    usd = lambda *entries: {"units": {"USD": list(entries)}}  # noqa: E731
    return {"facts": {"us-gaap": {
        "RevenueFromContractWithCustomerExcludingAssessedTax": usd(
            _e("2025-04-01", "2025-06-30", 119_575_000_000),   # quarter
            _e("2025-01-01", "2025-06-30", 230_000_000_000),   # year to date
            _e("2024-01-01", "2024-12-31", 400_000_000_000, form="10-K"),
        ),
        "OperatingIncomeLoss": usd(_e("2025-04-01", "2025-06-30", 40_373_000_000)),
        "NetIncomeLoss": usd(_e("2025-04-01", "2025-06-30", 33_916_000_000)),
        "NetCashProvidedByUsedInOperatingActivities": usd(
            _e("2025-04-01", "2025-06-30", 20_000_000_000),
            _e("2025-01-01", "2025-06-30", 55_000_000_000),    # cash flow statements are YTD
        ),
        "CashAndCashEquivalentsAtCarryingValue": usd(
            _e(None, "2024-12-31", 30_000_000_000, form="10-K"),
            _e(None, "2025-06-30", 40_760_000_000),
        ),
        "Assets": usd(_e(None, "2025-06-30", 353_514_000_000)),
    }}}


# Markdown as an extractor would return it (in millions, quarterly columns).
GOOD_MD = """
## Condensed Consolidated Statements of Operations
| | Three Months Ended |
|---|---|
| Total net sales | 119,575 |
| Operating income | 40,373 |
| Net income | 33,916 |

## Condensed Consolidated Balance Sheets
| | |
|---|---|
| Cash and cash equivalents | 40,760 |
| Total assets | 353,514 |

## Condensed Consolidated Statements of Cash Flows
| | Six Months Ended |
|---|---|
| Cash generated by operating activities | 55,000 |
"""

# Same statements, but the extractor garbled operating income and lost total assets.
BAD_MD = GOOD_MD.replace("40,373", "4O,373").replace("| Total assets | 353,514 |\n", "")


class FakeExtractor:
    def __init__(self, markdown, pages=6):
        self.markdown, self.pages = markdown, pages

    def extract(self, pdf_path):
        return {"markdown": self.markdown, "metadata": {"page_count": self.pages}}


class BrokenExtractor:
    def extract(self, pdf_path):
        raise RuntimeError("service down")


def test_edgar_truth_picks_quarter_ytd_and_instant_values():
    truth = edgar_truth(_facts(), period_end=date(2025, 6, 30), form="10-Q")

    assert truth["Revenue"] == 119_575_000_000          # 3-month, not YTD
    assert truth["CashFromOperations"] == 55_000_000_000  # YTD, like the statement
    assert truth["Cash"] == 40_760_000_000              # instant at period end
    assert truth["TotalAssets"] == 353_514_000_000
    assert "CapEx" not in truth                         # no XBRL fact -> not scored


def test_edgar_truth_for_annual_report():
    truth = edgar_truth(_facts(), period_end=date(2024, 12, 31), form="10-K")
    assert truth["Revenue"] == 400_000_000_000
    assert truth["Cash"] == 30_000_000_000


def test_markdown_numbers_handles_commas_parentheses_and_dollars():
    numbers = markdown_numbers("| Net loss | $(1,234.5) | 2025 | 17% |")
    assert -1234.5 in numbers
    assert 1234.5 in numbers  # sign-insensitive matching also needs the magnitude


def test_benchmark_scores_accuracy_and_recall():
    truth = edgar_truth(_facts(), period_end=date(2025, 6, 30), form="10-Q")

    results = run_benchmark(
        "filing.pdf", {"good": FakeExtractor(GOOD_MD), "bad": FakeExtractor(BAD_MD)}, truth, form="10-Q",
    )
    good, bad = results["good"], results["bad"]

    assert good.error is None
    assert good.scale == 1_000_000
    assert good.fields["Revenue"].correct            # mapper x4 annualization undone
    assert good.fields["CashFromOperations"].correct
    assert good.accuracy == pytest.approx(1.0)
    assert good.recall == pytest.approx(1.0)

    assert not bad.fields["EBIT"].correct
    assert not bad.fields["EBIT"].in_markdown       # extractor failure, not mapper failure
    assert not bad.fields["TotalAssets"].correct
    assert bad.accuracy == pytest.approx(4 / 6)


def test_benchmark_records_extractor_errors_and_cost():
    truth = edgar_truth(_facts(), period_end=date(2025, 6, 30), form="10-Q")

    results = run_benchmark(
        "filing.pdf",
        {"mistral": FakeExtractor(GOOD_MD, pages=10), "broken": BrokenExtractor()},
        truth, form="10-Q",
    )

    assert results["broken"].error == "RuntimeError: service down"
    assert results["broken"].accuracy == 0.0
    assert results["mistral"].estimated_cost_usd == pytest.approx(10 * 0.004)
    assert results["mistral"].seconds >= 0


def test_summarize_aggregates_across_filings():
    truth = edgar_truth(_facts(), period_end=date(2025, 6, 30), form="10-Q")
    run = lambda md: run_benchmark("f.pdf", {"x": FakeExtractor(md)}, truth, form="10-Q")  # noqa: E731

    summary = summarize([run(GOOD_MD), run(BAD_MD)])

    assert summary["x"]["filings"] == 2
    assert summary["x"]["accuracy"] == pytest.approx((6 + 4) / 12)
    assert summary["x"]["field_accuracy"]["EBIT"] == pytest.approx(0.5)


def test_run_manifest_records_failed_filings_and_continues():
    from counterfactual_oracle.src.parsers.benchmark import run_manifest

    class FlakySec:
        def company_facts(self, ticker):
            if ticker == "DOWN":
                raise ConnectionError("SEC dropped the connection")
            return _facts()

    cases = [
        {"pdf": "a.pdf", "ticker": "DOWN", "period_end": "2025-06-30", "form": "10-Q"},
        {"pdf": "b.pdf", "ticker": "OK", "period_end": "2025-06-30", "form": "10-Q"},
    ]
    seen = []

    filings, runs = run_manifest(cases, FlakySec(), {"x": FakeExtractor(GOOD_MD)}, on_filing=seen.append)

    assert filings[0]["error"] == "ConnectionError: SEC dropped the connection"
    assert filings[1]["results"]["x"]["accuracy"] == pytest.approx(1.0)
    assert len(runs) == 1  # only successful filings count toward the summary
    assert [f["ticker"] for f in seen] == ["DOWN", "OK"]  # progress reported as each finishes


def test_run_manifest_flags_filings_without_xbrl_ground_truth():
    from counterfactual_oracle.src.parsers.benchmark import run_manifest

    class Sec:
        def company_facts(self, ticker):
            return _facts()  # has no values for the requested period

    cases = [{"pdf": "a.pdf", "ticker": "KO", "period_end": "2026-07-03", "form": "10-Q"}]

    filings, runs = run_manifest(cases, Sec(), {"x": FakeExtractor(GOOD_MD)})

    assert "no XBRL values" in filings[0]["error"]
    assert runs == []  # must not count as a 0% score


def test_revenue_and_cogs_accept_any_standard_tag():
    # Caterpillar tags a minor $27M item as CostOfGoodsAndServicesSold and its real
    # cost of goods sold (8,965) as CostOfRevenue.
    from counterfactual_oracle.src.parsers.benchmark import truth_alternatives

    facts = _facts()
    gaap = facts["facts"]["us-gaap"]
    gaap["CostOfGoodsAndServicesSold"] = {"units": {"USD": [_e("2025-04-01", "2025-06-30", 27_000_000)]}}
    gaap["CostOfRevenue"] = {"units": {"USD": [_e("2025-04-01", "2025-06-30", 64_720_000_000)]}}
    period = date(2025, 6, 30)
    truth = edgar_truth(facts, period, "10-Q")
    alternatives = truth_alternatives(facts, period, "10-Q")
    markdown = GOOD_MD.replace("| Operating income", "| Total cost of sales | 64,720 |\n| Operating income")

    result = run_benchmark("f.pdf", {"x": FakeExtractor(markdown)}, truth, "10-Q", alternatives)["x"]

    assert truth["CostOfGoodsSold"] == 27_000_000       # primary tag is the odd one
    assert result.fields["CostOfGoodsSold"].correct       # but the real COGS is accepted
    assert "TotalEquity" not in alternatives              # equity stays strict (parent only)
